#!/usr/bin/env bash
# Buildroot flow for Raspberry Pi 5 with OpenSSH and Wi-Fi.
#
#   ./buildroot/br.sh all          # deps -> fetch -> configure -> build -> export
#   ./buildroot/br.sh <step>       # deps | fetch | configure | menuconfig | build | export | clean
#
# Analogy: Buildroot is a single Makefile-driven "recipe card". You pick a board
# card (raspberrypi5_defconfig), add your own ingredients (fragment below),
# and one `make` cooks toolchain + kernel + busybox rootfs + sdcard.img.

source "$(dirname "$0")/../common/lib.sh"

BR_SRC="$WORK_DIR/buildroot-$BUILDROOT_VERSION"
BR_OUT="$WORK_DIR/br-output"
BR_DL="$WORK_DIR/br-dl"                   # download cache, survives clean
BR_OVERLAY="$WORK_DIR/br-overlay"         # generated: holds your public key
BR_GEN="$WORK_DIR/br-generated"
BOARD_DIR="$REPO_ROOT/buildroot/board"

step_deps() {
    log "Installing host packages (sudo)"
    sudo apt-get update
    sudo apt-get install -y \
        build-essential gcc g++ make patch perl python3 rsync bc cpio unzip file \
        wget curl git sed binutils diffutils findutils gzip bzip2 xz-utils tar \
        libncurses-dev openssl openssh-client ccache \
        bmap-tools parted
    ok "Host dependencies installed"
}

step_fetch() {
    preflight 25 8
    if [[ -d "$BR_SRC/.git" ]]; then
        ok "Buildroot $BUILDROOT_VERSION already at $BR_SRC"
    else
        log "Cloning Buildroot $BUILDROOT_VERSION"
        git clone --depth 1 --branch "$BUILDROOT_VERSION" \
            https://gitlab.com/buildroot.org/buildroot.git "$BR_SRC" \
          || git clone --depth 1 --branch "$BUILDROOT_VERSION" \
            https://github.com/buildroot/buildroot.git "$BR_SRC"
    fi
    [[ -f "$BR_SRC/configs/raspberrypi5_defconfig" ]] \
        || die "raspberrypi5_defconfig missing in $BR_SRC"
    ok "Base board config: configs/raspberrypi5_defconfig"
}

step_configure() {
    preflight 25 8
    [[ -d "$BR_SRC" ]] || step_fetch
    ensure_ssh_key
    make_root_hash

    # 1) Rootfs overlay: files copied verbatim on top of the target rootfs.
    log "Preparing rootfs overlay"
    rm -rf "$BR_OVERLAY"
    install -d -m 0700 "$BR_OVERLAY/root/.ssh"
    install -m 0600 "$SSH_PUBKEY" "$BR_OVERLAY/root/.ssh/authorized_keys"
    cp -a "$BOARD_DIR/overlay/." "$BR_OVERLAY/"
    make_wifi_conf "$BR_OVERLAY/etc/wpa_supplicant.conf"   # replaces the package's sample
    install -D -m 0755 "$REPO_ROOT/common/target/rootfs-expand" "$BR_OVERLAY/usr/sbin/rootfs-expand"

    # 2) Our additions on top of the stock Pi 5 defconfig.
    #    In .config files make expands '$', so the hash's '$' must be doubled.
    local hash_mk="${ROOT_HASH//\$/\$\$}"
    mkdir -p "$BR_GEN"
    cat > "$BR_GEN/mylab.fragment" <<EOF
# ---- MyLab additions (generated by br.sh) ----
BR2_DL_DIR="$BR_DL"
BR2_CCACHE=y
BR2_CCACHE_DIR="$WORK_DIR/br-ccache"
BR2_TARGET_GENERIC_HOSTNAME="$RPI_HOSTNAME"
BR2_TARGET_GENERIC_ISSUE="Welcome to $RPI_HOSTNAME (Buildroot $BUILDROOT_VERSION)"
BR2_TARGET_ENABLE_ROOT_LOGIN=y
BR2_TARGET_GENERIC_ROOT_PASSWD="$hash_mk"
BR2_PACKAGE_OPENSSH=y
BR2_PACKAGE_OPENSSH_SERVER=y
BR2_PACKAGE_OPENSSH_CLIENT=y
BR2_PACKAGE_OPENSSH_KEY_UTILS=y
BR2_ROOTFS_OVERLAY="$BR_OVERLAY"
BR2_ROOTFS_POST_BUILD_SCRIPT="board/raspberrypi5/post-build.sh $BOARD_DIR/post-build.sh"
BR2_ROOTFS_POST_BUILD_SCRIPT_ARGS="$ALLOW_ROOT_PASSWORD_SSH"
BR2_TARGET_ROOTFS_EXT2_SIZE="256M"
# Wi-Fi (CYW43455 on SDIO, brcmfmac driver). The stock defconfig has neither the
# firmware nor a device manager; without mdev nothing loads brcmfmac on boot.
BR2_ROOTFS_DEVICE_CREATION_DYNAMIC_MDEV=y
BR2_PACKAGE_BRCMFMAC_SDIO_FIRMWARE_RPI=y
BR2_PACKAGE_BRCMFMAC_SDIO_FIRMWARE_RPI_WIFI=y
BR2_PACKAGE_WIRELESS_REGDB=y
BR2_PACKAGE_IW=y
BR2_PACKAGE_WPA_SUPPLICANT=y
BR2_PACKAGE_WPA_SUPPLICANT_NL80211=y
BR2_PACKAGE_WPA_SUPPLICANT_CTRL_IFACE=y
BR2_PACKAGE_WPA_SUPPLICANT_CLI=y
BR2_PACKAGE_WPA_SUPPLICANT_PASSPHRASE=y
# First boot: grow / to the card size (S05rootfs-expand). sfdisk is in the
# util-linux "basic set"; partx and resize2fs are separate options.
BR2_PACKAGE_UTIL_LINUX=y
BR2_PACKAGE_UTIL_LINUX_BINARIES=y
BR2_PACKAGE_UTIL_LINUX_PARTX=y
BR2_PACKAGE_E2FSPROGS=y
BR2_PACKAGE_E2FSPROGS_RESIZE2FS=y
# mDNS: reachable as $RPI_HOSTNAME.local, and the SSH service is advertised.
BR2_PACKAGE_AVAHI=y
BR2_PACKAGE_AVAHI_DAEMON=y
BR2_PACKAGE_AVAHI_DEFAULT_SERVICES=y
# NTP: no RTC battery by default, so the clock is wrong after every power-off.
BR2_PACKAGE_CHRONY=y
# Boot overlays (overlays/ on the FAT partition). The stock defconfig leaves them
# out, but newer Pi 5 boards (Rev 1.1, D0 chip) need overlays/bcm2712d0.dtbo:
# without it the kernel gets the C1 pin layout and panics (SError in
# bcm2712_pull_config_set) about 1.5 s into boot.
BR2_PACKAGE_RPI_FIRMWARE_INSTALL_DTB_OVERLAYS=y
EOF

    # 3) Base defconfig + fragment. For duplicated symbols Kconfig keeps the
    #    LAST value, so our fragment wins.
    cat "$BR_SRC/configs/raspberrypi5_defconfig" "$BR_GEN/mylab.fragment" \
        > "$BR_GEN/mylab_rpi5_defconfig"
    chmod 600 "$BR_GEN/mylab_rpi5_defconfig"   # contains the password hash

    log "Applying configuration (out-of-tree: $BR_OUT)"
    make -C "$BR_SRC" O="$BR_OUT" BR2_DEFCONFIG="$BR_GEN/mylab_rpi5_defconfig" defconfig

    # 4) Verify the important options actually stuck.
    local c="$BR_OUT/.config"
    for sym in BR2_PACKAGE_OPENSSH=y BR2_PACKAGE_OPENSSH_SERVER=y \
               BR2_PACKAGE_RPI_FIRMWARE=y BR2_cortex_a76=y \
               BR2_ROOTFS_DEVICE_CREATION_DYNAMIC_MDEV=y \
               BR2_PACKAGE_BRCMFMAC_SDIO_FIRMWARE_RPI_WIFI=y \
               BR2_PACKAGE_WPA_SUPPLICANT=y BR2_PACKAGE_WPA_SUPPLICANT_NL80211=y \
               BR2_PACKAGE_UTIL_LINUX_BINARIES=y BR2_PACKAGE_UTIL_LINUX_PARTX=y \
               BR2_PACKAGE_E2FSPROGS_RESIZE2FS=y BR2_PACKAGE_AVAHI_DAEMON=y \
               BR2_PACKAGE_CHRONY=y BR2_PACKAGE_RPI_FIRMWARE_INSTALL_DTB_OVERLAYS=y; do
        grep -qx "$sym" "$c" || die "Expected $sym in .config"
    done
    grep -q "^BR2_TARGET_GENERIC_HOSTNAME=\"$RPI_HOSTNAME\"" "$c" || die "hostname not applied"
    ok "Configured: Pi 5 (Cortex-A76, bcm2712 kernel) + OpenSSH + Wi-Fi + mDNS + NTP, hostname $RPI_HOSTNAME"
}

step_menuconfig() {
    sanitize_path
    make -C "$BR_SRC" O="$BR_OUT" menuconfig
    log "Tip: 'make -C $BR_SRC O=$BR_OUT savedefconfig' writes the minimal defconfig."
}

step_build() {
    preflight 25 8
    [[ -f "$BR_OUT/.config" ]] || step_configure
    log "Building with $JOBS jobs — first build ~30-90 min, log in $BR_OUT/build.log"
    local t0=$SECONDS
    # Buildroot parallelises inside each package; top-level -j is not supported.
    make -C "$BR_SRC" O="$BR_OUT" BR2_JLEVEL="$JOBS" 2>&1 | tee "$BR_OUT/build.log"
    local img="$BR_OUT/images/sdcard.img"
    [[ -f "$img" ]] || die "No sdcard.img produced, see $BR_OUT/build.log"
    ok "Built $(du -h "$img" | cut -f1) image in $(( (SECONDS - t0) / 60 )) min: $img"

    # Quick sanity check of what's inside the rootfs.
    local t="$BR_OUT/target"
    [[ -x "$t/usr/sbin/sshd" ]]                    && ok "sshd present"            || die "sshd missing"
    [[ -f "$t/root/.ssh/authorized_keys" ]]        && ok "authorized_keys present" || die "authorized_keys missing"
    compgen -G "$t/etc/init.d/S*sshd" >/dev/null   && ok "sshd init script present" || die "sshd init script missing"
    [[ -x "$t/usr/sbin/wpa_supplicant" ]]          && ok "wpa_supplicant present"  || die "wpa_supplicant missing"
    [[ -x "$t/etc/init.d/S45wifi" ]]               && ok "Wi-Fi init script present" || die "S45wifi missing"
    [[ -f "$t/etc/wpa_supplicant.conf" ]]          && ok "wpa_supplicant.conf present" || die "wpa_supplicant.conf missing"
    compgen -G "$t/lib/modules/*/kernel/drivers/net/wireless/broadcom/brcm80211/brcmfmac/brcmfmac.ko*" >/dev/null \
        && ok "brcmfmac driver present" || warn "brcmfmac.ko not found in /lib/modules (built into the kernel?)"
    compgen -G "$t/lib/firmware/brcm/brcmfmac43455-sdio*" >/dev/null \
        && ok "CYW43455 Wi-Fi firmware present" || warn "No brcmfmac43455 firmware in /lib/firmware/brcm"

    local bin d found s
    for bin in sfdisk partx resize2fs rootfs-expand avahi-daemon chronyd; do
        found=""
        for d in usr/sbin sbin usr/bin bin; do
            [[ -x "$t/$d/$bin" ]] && { found="/$d/$bin"; break; }
        done
        [[ -n "$found" ]] || die "$bin missing from the rootfs"
    done
    ok "rootfs-expand (sfdisk, partx, resize2fs), avahi-daemon, chronyd present"
    for s in S05rootfs-expand S49chronyd S50avahi-daemon; do
        [[ -x "$t/etc/init.d/$s" ]] || die "init script $s missing"
    done
    ok "First-boot resize, NTP and mDNS init scripts present"
}

step_export() {
    local img="$BR_OUT/images/sdcard.img"
    [[ -f "$img" ]] || die "Build first: $img not found"
    local named="$BR_OUT/images/${RPI_HOSTNAME}-buildroot-${BUILDROOT_VERSION}.img"
    cp -f "$img" "$named"
    export_to_windows "$named"
    cat <<EOF

Next:
  1. Flash from WSL:     ./tools/flash.sh buildroot
     (or from Windows: Raspberry Pi Imager -> "Use custom", NO OS customisation)
  2. Plug the Pi 5 into Ethernet (or rely on Wi-Fi: ${WIFI_SSID:-not configured}), power on, wait ~20 s.
  3. ./tools/verify-ssh.sh               (finds $RPI_HOSTNAME.local, else scans the LAN)
EOF
}

step_clean() {
    log "Removing $BR_OUT (downloads in $BR_DL are kept)"
    rm -rf "$BR_OUT"
}

case "${1:-all}" in
    deps)       step_deps ;;
    fetch)      step_fetch ;;
    configure)  step_configure ;;
    menuconfig) step_menuconfig ;;
    build)      step_build ;;
    export)     step_export ;;
    clean)      step_clean ;;
    all)        step_fetch; step_configure; step_build; step_export ;;
    *) die "Unknown step '$1'. Use: deps fetch configure menuconfig build export clean all" ;;
esac
